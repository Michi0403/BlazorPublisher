param(
    [string]$DocumentationRoot = "",
    [string]$OutputArchive = ""
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$repositoryRoot = Split-Path -Parent $PSScriptRoot
$projectFile = Join-Path $repositoryRoot "src\PublisherStudio.Web\PublisherStudio.Web.csproj"
if (-not (Test-Path -LiteralPath $projectFile -PathType Leaf)) {
    throw "PublisherStudio project file was not found: $projectFile"
}

[xml]$project = Get-Content -LiteralPath $projectFile -Raw
$expectedVersion = @(
    $project.Project.PropertyGroup |
        ForEach-Object { [string]$_.Version } |
        Where-Object { -not [string]::IsNullOrWhiteSpace($_) }
) | Select-Object -First 1
if ([string]::IsNullOrWhiteSpace([string]$expectedVersion)) {
    throw "PublisherStudio source version could not be resolved from $projectFile"
}
$expectedVersion = ([string]$expectedVersion).Trim()

if ([string]::IsNullOrWhiteSpace($DocumentationRoot)) {
    $releaseRoot = Join-Path $repositoryRoot "src\PublisherStudio.Web\bin\Release\net10.0\wwwroot\help-docs"
    $debugRoot = Join-Path $repositoryRoot "src\PublisherStudio.Web\bin\Debug\net10.0\wwwroot\help-docs"
    $DocumentationRoot = if (Test-Path -LiteralPath $releaseRoot -PathType Container) { $releaseRoot } else { $debugRoot }
}
$DocumentationRoot = [IO.Path]::GetFullPath($DocumentationRoot)
if (-not (Test-Path -LiteralPath $DocumentationRoot -PathType Container)) {
    throw "Generated PublisherStudio documentation was not found: $DocumentationRoot"
}

if ([string]::IsNullOrWhiteSpace($OutputArchive)) {
    $OutputArchive = Join-Path $repositoryRoot ".github\pages\publisherstudio-kawaii-docs.zip"
}
$OutputArchive = [IO.Path]::GetFullPath($OutputArchive)
$outputDirectory = Split-Path -Parent $OutputArchive
New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null

$validator = Join-Path $repositoryRoot ".github\scripts\prepare-pages-artifact.py"
if (-not (Test-Path -LiteralPath $validator -PathType Leaf)) {
    throw "PublisherStudio GitHub Pages validator was not found: $validator"
}
$python = Get-Command python -ErrorAction SilentlyContinue
if ($null -eq $python) { $python = Get-Command python3 -ErrorAction SilentlyContinue }
if ($null -eq $python) { throw "Python 3 is required to validate the GitHub Pages snapshot." }

$operationId = [Guid]::NewGuid().ToString("N")
$preparedRoot = Join-Path ([IO.Path]::GetTempPath()) ("PublisherStudio-Pages-Prepared-" + $operationId)
$verificationRoot = Join-Path ([IO.Path]::GetTempPath()) ("PublisherStudio-Pages-Verify-" + $operationId)
$temporaryArchive = "$OutputArchive.$operationId.tmp"
$backupArchive = "$OutputArchive.$operationId.backup"
$installed = $false

try {
    & $python.Source $validator --source $DocumentationRoot --output $preparedRoot
    if ($LASTEXITCODE -ne 0) {
        throw "Generated PublisherStudio documentation did not pass the GitHub Pages validator."
    }

    $statusPath = Join-Path $preparedRoot "documentation-status.json"
    $status = Get-Content -LiteralPath $statusPath -Raw | ConvertFrom-Json
    if ([string]$status.version -ne $expectedVersion) {
        throw "Generated documentation version '$($status.version)' does not match PublisherStudio source version '$expectedVersion'."
    }
    $expectedPdf = Join-Path $preparedRoot "PublisherStudio-$expectedVersion.pdf"
    if (-not (Test-Path -LiteralPath $expectedPdf -PathType Leaf)) {
        throw "Generated documentation does not contain the current versioned PDF: $expectedPdf"
    }

    # Deployment metadata is generated by the workflow; it is not part of the pinned source snapshot.
    Remove-Item -LiteralPath (Join-Path $preparedRoot "github-pages-deployment.json") -Force -ErrorAction SilentlyContinue

    Add-Type -AssemblyName System.IO.Compression.FileSystem -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $temporaryArchive -Force -ErrorAction SilentlyContinue
    $files = @(Get-ChildItem -LiteralPath $preparedRoot -File -Recurse | Sort-Object FullName)
    if ($files.Count -eq 0) { throw "Prepared PublisherStudio GitHub Pages tree is empty." }

    $stream = [IO.File]::Open($temporaryArchive, [IO.FileMode]::CreateNew, [IO.FileAccess]::ReadWrite, [IO.FileShare]::None)
    try {
        $archive = [IO.Compression.ZipArchive]::new($stream, [IO.Compression.ZipArchiveMode]::Create, $true)
        try {
            foreach ($file in $files) {
                $relative = $file.FullName.Substring($preparedRoot.Length).TrimStart([char[]]"\/").Replace('\', '/')
                if ([string]::IsNullOrWhiteSpace($relative) -or $relative.StartsWith('/', [StringComparison]::Ordinal) -or $relative.Split('/') -contains '..') {
                    throw "Unsafe GitHub Pages archive path: $relative"
                }

                $written = $false
                $lastReadError = $null
                for ($attempt = 1; $attempt -le 4 -and -not $written; $attempt++) {
                    $entry = $null
                    try {
                        $input = [IO.File]::Open($file.FullName, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::ReadWrite -bor [IO.FileShare]::Delete)
                        try {
                            $entry = $archive.CreateEntry($relative, [IO.Compression.CompressionLevel]::Optimal)
                            $entry.LastWriteTime = [DateTimeOffset]::new(1980, 1, 1, 0, 0, 0, [TimeSpan]::Zero)
                            $output = $entry.Open()
                            try { $input.CopyTo($output) }
                            finally { $output.Dispose() }
                        }
                        finally { $input.Dispose() }
                        $written = $true
                    }
                    catch {
                        $lastReadError = $_.Exception
                        if ($null -ne $entry) { try { $entry.Delete() } catch { } }
                        if ($attempt -lt 4) { Start-Sleep -Milliseconds (150 * $attempt) }
                    }
                }
                if (-not $written) {
                    throw "Could not add GitHub Pages file '$($file.FullName)' after 4 attempts: $($lastReadError.Message)"
                }
            }
        }
        finally { $archive.Dispose() }
    }
    finally { $stream.Dispose() }

    & $python.Source $validator --archive $temporaryArchive --output $verificationRoot
    if ($LASTEXITCODE -ne 0) {
        throw "The new PublisherStudio GitHub Pages snapshot did not pass final validation."
    }
    $verifiedStatus = Get-Content -LiteralPath (Join-Path $verificationRoot "documentation-status.json") -Raw | ConvertFrom-Json
    if ([string]$verifiedStatus.version -ne $expectedVersion) {
        throw "The verified Pages archive version '$($verifiedStatus.version)' does not match '$expectedVersion'."
    }

    Remove-Item -LiteralPath $backupArchive -Force -ErrorAction SilentlyContinue
    if (Test-Path -LiteralPath $OutputArchive -PathType Leaf) {
        [IO.File]::Move($OutputArchive, $backupArchive)
    }
    try {
        [IO.File]::Move($temporaryArchive, $OutputArchive)
        $installed = $true
    }
    catch {
        if (Test-Path -LiteralPath $backupArchive -PathType Leaf) {
            [IO.File]::Move($backupArchive, $OutputArchive)
        }
        throw
    }
    Remove-Item -LiteralPath $backupArchive -Force -ErrorAction SilentlyContinue

    $hash = (Get-FileHash -LiteralPath $OutputArchive -Algorithm SHA256).Hash.ToLowerInvariant()
    Write-Host "Updated PublisherStudio $expectedVersion GitHub Pages snapshot: $OutputArchive" -ForegroundColor Green
    Write-Host "SHA-256: $hash" -ForegroundColor Green
}
finally {
    Remove-Item -LiteralPath $preparedRoot -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $verificationRoot -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $temporaryArchive -Force -ErrorAction SilentlyContinue
    if (-not $installed -and (Test-Path -LiteralPath $backupArchive -PathType Leaf) -and -not (Test-Path -LiteralPath $OutputArchive -PathType Leaf)) {
        [IO.File]::Move($backupArchive, $OutputArchive)
    }
}
