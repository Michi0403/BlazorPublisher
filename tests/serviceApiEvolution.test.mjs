import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), 'utf8');
const composition = read('src','PublisherStudio.Web','PublisherStudioServiceCollectionExtensions.cs');
const program = read('src','PublisherStudio.Web','Program.cs');
const context = read('src','PublisherStudio.Web','Services','Automation','BusinessObjectContextService.cs');
